#!/usr/bin/env python3
"""End-to-end benchmark of `codna fix` on real public repos — writes a Markdown report incrementally.

Runs `codna fix <repo> --issue "..."` (inspect mode: triage -> agentic decision plan -> patch ref,
no apply) against a live engine + agent-core sidecar (real Cline, real LLM), and records per repo:
localized symbol + blast radius, confidence, regression risk, context-token reduction, agent model,
USD cost, wall time, the patch ref, and status. Real CLI, no mocks/stubs. The report is written to
OUT after EACH repo so partial progress persists (and lands in the repo, not a temp folder).

Env: CODNA_API_KEY (Codna account), CODNA_BIN (codna entrypoint), CODNA_TIMEOUT_S (client),
     BENCHMARK_OUT (output path; default: alongside this file).
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import time
from datetime import datetime, timezone

from bench_env import bench_repos_root, resolve_bin

HERE = os.path.dirname(os.path.abspath(__file__))
# Label for the model under test (the engine's ALGENTA_AGENT_MODEL); used in the title + the JSON
# sidecar so per-model runs can be merged into one cross-model comparison (benchmark_fix_compare.py).
MODEL = os.environ.get("BENCH_MODEL", "claude-sonnet-4-6")
_SLUG = re.sub(r"[^a-z0-9.-]+", "-", MODEL.lower())
OUT = os.environ.get("BENCHMARK_OUT", os.path.join(HERE, f"BENCHMARK-fix-{_SLUG}.md"))
OUT_JSON = os.path.join(HERE, f".fix-results-{_SLUG}.json")

CASES = [
    ("requests", "Session.send does not retry when the underlying connection times out; add a retry-on-timeout path"),
    ("click", "a required option in a command group does not raise a clear error when omitted"),
    ("flask", "send_file returns the wrong content-type for .webp files"),
    ("httpx", "the connection pool is not released when a streaming response is closed early"),
    ("rich", "Table column width is miscalculated when a cell contains wide (CJK) unicode characters"),
]


def _g(pat, text, d="—"):
    m = re.search(pat, text)
    return m.group(1).strip() if m else d


def _codna_bin() -> str:
    """Absolute path of the codna entrypoint: ``$CODNA_BIN`` or ``codna`` on PATH.

    Validated when the benchmark runs (allowlisted name on PATH, or an absolute existing
    executable), never at import, so the module stays importable where codna is not installed;
    a missing or unvetted binary still fails clearly before any repo is run.
    """
    return resolve_bin("CODNA_BIN", "codna", allowed=("codna",))


def render(rows, transcripts, done, total) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    o = [f"# `codna fix` benchmark — real public repos ({MODEL})\n",
         f"_Generated {now} · model: **{MODEL}** · live engine + agent-core sidecar (real Cline, real LLM) · "
         f"inspect mode (triage → agent plan → patch ref, no apply) · {done}/{total} repos._\n",
         "> Each row is one real agent run (real model + USD cost) over the engine's deterministic triage "
         "+ the agentic Cline decision plan. No mocks. Idle/no-progress timeout only — runs are bounded by "
         "agent turns, not a wall clock.\n",
         "## Results\n",
         "| Repo | Localized symbol | Blast | Confidence | Regression risk | Context reduction | Model | Cost | Time | Patch | Status |",
         "|---|---|---|--:|--:|---|---|--:|--:|---|---|"]
    for r in rows:
        o.append("| " + " | ".join(r) + " |")
    o.append("\n## Transcripts (real output)\n")
    for name, issue, out in transcripts:
        o.append(f"### {name} — _{issue}_\n```text\n{out}\n```\n")
    o.append("## Method\n- `codna fix <repo> --issue \"…\"` (inspect mode) against a live engine + agent-core "
             "sidecar; the agentic patch is generated by the vendored Cline SDK.\n- Metrics parsed from real "
             "CLI output; cost/model are what the agent actually used.\n- Issues are realistic, plausible bugs "
             "(not planted) — measures localization + planning quality, not a known-answer pass/fail.\n")
    return "\n".join(o)


def main(argv=None) -> int:
    codna = _codna_bin()
    base = bench_repos_root(argv)  # first CLI arg (else /tmp/bench-repos); must be a directory
    rows, transcripts = [], []
    cases = [(n, i) for n, i in CASES if os.path.isdir(os.path.join(base, n))]
    for idx, (name, issue) in enumerate(cases, 1):
        repo = os.path.join(base, name)
        t = time.perf_counter()
        p = subprocess.run([codna, "fix", repo, "--issue", issue], capture_output=True, text=True)
        wall = time.perf_counter() - t
        out = (p.stdout + p.stderr).strip()
        rows.append((name,
                     _g(r"symbol\s*:\s*(.+?)\s*\(blast radius", out),
                     _g(r"blast radius:\s*([a-z]+)", out),
                     _g(r"confidence\s*:\s*(\d+%)", out),
                     _g(r"regression risk:\s*(\d+%)", out),
                     _g(r"context\s*:\s*([\d,]+ → [\d,]+ tokens\s*\([\d.]+× smaller\))", out),
                     _g(r"agent\s*:\s*([\w.-]+)", out),
                     _g(r"cost:\s*(\$[\d.]+)", out),
                     f"{wall:.0f}s",
                     _g(r"patch\s*:\s*(patch_[\w]+)", out),
                     "ok" if p.returncode == 0 else f"exit {p.returncode}"))
        transcripts.append((name, issue, out))
        with open(OUT, "w") as f:                       # write after EACH repo (persist partial progress)
            f.write(render(rows, transcripts, idx, len(cases)))
        print(f"[{idx}/{len(cases)}] {name}: {rows[-1][9]} ({rows[-1][8]}, {rows[-1][7]}) -> {OUT}")
    # JSON sidecar (per-model) so benchmark_fix_compare.py can build a cross-model comparison.
    keys = ("repo", "symbol", "blast", "confidence", "regression", "context", "agent", "cost", "time", "patch", "status")
    with open(OUT_JSON, "w") as f:
        json.dump({"model_label": MODEL, "rows": [dict(zip(keys, r)) for r in rows]}, f, indent=2)
    print(f"done -> {OUT}  (+ {OUT_JSON})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
